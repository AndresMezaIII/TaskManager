class Task {
  constructor(title, description, color, date, status, budget) {
    this.title = title;
    //this is not passing variables, it is taking the content of the variable and places it in another space inside of the memory
    this.description = description;
    this.color = color;
    this.date = date;
    this.status = status;
    this.budget = budget;
  }
}
